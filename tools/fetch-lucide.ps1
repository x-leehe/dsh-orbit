# 从 lucide-static 拉取官方 SVG，并生成 LucideData.cs（图标名 → 形状描述）。
# 形状描述格式：
#   P|<svg path d>           路径
#   R|x|y|w|h|rx             圆角矩形
#   C|cx|cy|r                圆
#   L|x1|y1|x2|y2            线
#   O|"x,y x,y ..."          折线
#   G|"x,y x,y ..."          多边形
[CmdletBinding()]
param(
    [string]$OutFile = (Join-Path $PSScriptRoot '..\LucideData.cs'),
    [string]$SvgDir  = (Join-Path $PSScriptRoot '..\assets\lucide')
)

$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force -Path $SvgDir | Out-Null

# C# 里用的名字 → lucide 官方图标文件名
$icons = [ordered]@{
    'activity'      = 'activity'
    'play'          = 'play'
    'pause'         = 'pause'
    'external'      = 'external-link'
    'refresh'       = 'refresh-cw'
    'square'        = 'square'
    'minus'         = 'minus'
    'x'             = 'x'
    'plus'          = 'plus'
    'pin'           = 'pin'
    'lock'          = 'lock'
    'eye'           = 'eye'
    'eye-off'       = 'eye-off'
    'copy'          = 'copy'
    'file-text'     = 'file-text'
    'power'         = 'power'
    'panel-bottom'  = 'panel-bottom'
    'panel-left'    = 'panel-left'
    'monitor'       = 'monitor'
    'zap'           = 'zap'
    'app-window'    = 'app-window'
    'chevron-down'  = 'chevron-down'
    'chevron-up'    = 'chevron-up'
    'circle-stop'   = 'circle-stop'
    'check'         = 'check'
    'search'        = 'search'
}

function Convert-SvgToSpec([string]$svg) {
    $specs = New-Object System.Collections.Generic.List[string]

    foreach ($m in [regex]::Matches($svg, '<path\s+[^>]*d="([^"]+)"')) {
        $d = $m.Groups[1].Value -replace '\s+', ' '
        $specs.Add("P|$($d.Trim())")
    }

    foreach ($m in [regex]::Matches($svg, '<rect\s+([^/>]+)')) {
        $attrs = $m.Groups[1].Value
        $get = {
            param($name, $default)
            $mm = [regex]::Match($attrs, "$name=""([^""]+)""")
            if ($mm.Success) { [double]::Parse($mm.Groups[1].Value, [Globalization.CultureInfo]::InvariantCulture) } else { $default }
        }
        $x = & $get 'x' 0
        $y = & $get 'y' 0
        $w = & $get 'width' 0
        $h = & $get 'height' 0
        $rx = & $get 'rx' 0
        $specs.Add("R|$x|$y|$w|$h|$rx")
    }

    foreach ($m in [regex]::Matches($svg, '<circle\s+([^/>]+)')) {
        $attrs = $m.Groups[1].Value
        $cx = [double]::Parse([regex]::Match($attrs, 'cx="([^"]+)"').Groups[1].Value, [Globalization.CultureInfo]::InvariantCulture)
        $cy = [double]::Parse([regex]::Match($attrs, 'cy="([^"]+)"').Groups[1].Value, [Globalization.CultureInfo]::InvariantCulture)
        $r  = [double]::Parse([regex]::Match($attrs, 'r="([^"]+)"').Groups[1].Value, [Globalization.CultureInfo]::InvariantCulture)
        $specs.Add("C|$cx|$cy|$r")
    }

    foreach ($m in [regex]::Matches($svg, '<line\s+([^/>]+)')) {
        $attrs = $m.Groups[1].Value
        $x1 = [regex]::Match($attrs, 'x1="([^"]+)"').Groups[1].Value
        $y1 = [regex]::Match($attrs, 'y1="([^"]+)"').Groups[1].Value
        $x2 = [regex]::Match($attrs, 'x2="([^"]+)"').Groups[1].Value
        $y2 = [regex]::Match($attrs, 'y2="([^"]+)"').Groups[1].Value
        if ($x1 -and $y1 -and $x2 -and $y2) { $specs.Add("L|$x1|$y1|$x2|$y2") }
    }

    foreach ($m in [regex]::Matches($svg, '<polyline\s+[^>]*points="([^"]+)"')) {
        $specs.Add("O|$($m.Groups[1].Value)")
    }

    foreach ($m in [regex]::Matches($svg, '<polygon\s+[^>]*points="([^"]+)"')) {
        $specs.Add("G|$($m.Groups[1].Value)")
    }

    return $specs
}

$entries = New-Object System.Collections.Generic.List[string]
foreach ($name in $icons.Keys) {
    $file = $icons[$name]
    $url = "https://cdn.jsdelivr.net/npm/lucide-static@latest/icons/$file.svg"
    $svgPath = Join-Path $SvgDir "$file.svg"
    if (-not (Test-Path $svgPath)) {
        Write-Host "fetch $file ..."
        $svg = (Invoke-WebRequest $url -UseBasicParsing -TimeoutSec 30).Content
        # 只保留 svg 主体，去掉 license 注释里的可变版本号
        $svg = $svg -replace '<!--[\s\S]*?-->', ''
        Set-Content -Path $svgPath -Value $svg -Encoding UTF8
    }
    $svg = Get-Content $svgPath -Raw
    $specs = Convert-SvgToSpec $svg
    if ($specs.Count -eq 0) { throw "no shapes parsed for $file" }

    $entry = [System.Text.StringBuilder]::new()
    [void]$entry.Append("        [""$name""] = new[]`n        {`n")
    foreach ($s in $specs) {
        [void]$entry.Append("            `"$s`",`n")
    }
    [void]$entry.Append("        },`n")
    $entries.Add($entry.ToString())
    Write-Host ("  {0,-14} {1} shapes" -f $name, $specs.Count)
}

$header = @"
// <auto-generated>
// 由 tools/fetch-lucide.ps1 生成：lucide-static（ISC License）官方 SVG 的几何数据。
// 不要手改，改脚本后重跑。
// </auto-generated>
namespace DshOrbit;

internal static partial class LucideData
{
    /// <summary>图标名 → 形状描述（P=path，R=rect，C=circle，L=line，O=polyline，G=polygon）。</summary>
    internal static readonly Dictionary<string, string[]> Shapes = new()
    {
"@

$footer = @"
    };
}
"@

$content = $header + ($entries -join '') + $footer
Set-Content -Path $OutFile -Value $content -Encoding UTF8
Write-Host "wrote $OutFile ($($entries.Count) icons)"
